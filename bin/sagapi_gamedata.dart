class DecodeTaskPayload {
  final List<String> filePaths;
  final String schemasDir;
  final int isolateId;

  DecodeTaskPayload(this.filePaths, this.schemasDir, this.isolateId);
}

Future<void> _processChunkInIsolate(
  DecodeTaskPayload payload, {
  bool verbose = false,
  bool failfast = false,
}) async {
  int successCount = 0;
  for (String filePath in payload.filePaths) {
    final file = File(filePath);
    if (file.existsSync()) {
      bool result = await GamedataDecoder.processFile(
        file,
        payload.schemasDir,
        verbose: verbose,
        failfast: failfast,
      );
      if (result) successCount++;
    }
  }
  print('[ISO-${payload.isolateId}] Process completed: $successCount files decoded successfully.');
}

/// Moves the content of 'dyn/' to the server root and copies hot_update_list.json
void _restructureOutput(String server, String outputRoot, String bundlesRoot) {
  final serverOutDir = Directory(p.join(outputRoot, server));
  final dynDir = Directory(p.join(serverOutDir.path, 'dyn'));
  final assetsDir = Directory(p.join(serverOutDir.path, 'assets'));

  // Flatten the 'dyn' directory structure
  if (dynDir.existsSync()) {
    print('[INFO] Restructuring directories for $server...');
    for (var entity in dynDir.listSync()) {
      final newPath = p.join(serverOutDir.path, p.basename(entity.path));
      // Overwrite if it already exists from a previous run
      if (FileSystemEntity.typeSync(newPath) != FileSystemEntityType.notFound) {
        if (entity is Directory) Directory(newPath).deleteSync(recursive: true);
        if (entity is File) File(newPath).deleteSync();
      }
      entity.renameSync(newPath);
    }
    dynDir.deleteSync(recursive: true);
  }

  // Clean up the useless 'assets' folder generated by the container
  if (assetsDir.existsSync()) {
    assetsDir.deleteSync(recursive: true);
  }

  // Copy hot_update_list.json to the server root
  final hotUpdateSrc = File(p.join(bundlesRoot, server, 'hot_update_list.json'));
  final hotUpdateDest = File(p.join(serverOutDir.path, 'hot_update_list.json'));

  if (hotUpdateSrc.existsSync()) {
    hotUpdateSrc.copySync(hotUpdateDest.path);
    print('[OK] hot_update_list.json copied successfully to server root.');
  } else {
    print('[WARN] hot_update_list.json not found in temporary bundles.');
  }
}

ArgParser buildParser() {
  return ArgParser()
    ..addOption('server', allowed: ['all', 'cn', 'en', 'jp', 'kr', 'tw'], defaultsTo: 'all')
    ..addOption('bundles-path', defaultsTo: './gamedata_tmp_bundles')
    ..addOption('out-path', defaultsTo: './gamedata_final')
    ..addFlag('verbose', abbr: 'v', defaultsTo: false)
    ..addFlag(
      'failfast',
      abbr: 'd',
      defaultsTo: false,
    ) // errors end program, useful to deactivate on development
    ..addFlag('force', abbr: 'f', defaultsTo: false);
}

void printUsage(ArgParser argParser) {
  print('Usage: dart sagapi_gamedata.dart <flags> [arguments]');
  print(argParser.usage);
}

void main(List<String> arguments) async {
  final parser = buildParser();

  ArgResults argResults;
  try {
    argResults = parser.parse(arguments);
  } on FormatException catch (e) {
    print(e.message);
    print('');
    printUsage(parser);
    exit(1);
  } catch (e) {
    print('[ERROR] Argument parsing: $e');
    exit(1);
  }

  final String targetServer = argResults['server'];
  final String bundlesRoot = argResults['bundles-path'];
  final String outputRoot = argResults['out-path'];
  final bool forceUpdate = argResults['force'];
  final bool verbose = argResults['verbose'];
  final bool failfast = argResults['failfast'];

  List<String> serversToProcess = targetServer == 'all'
      ? ['cn', 'en', 'jp', 'kr', 'tw']
      : [targetServer];

  print('=== Starting Sagapi GameData Extractor ===');

  await StudioManager.ensureStudioInstalled();
  await FlatcManager.ensureFlatcInstalled();

  for (String server in serversToProcess) {
    print('\n--- Processing Server: ${server.toUpperCase()} ---');

    final networkInfo = await ArknightsNetwork.fetchAssetBaseUrl(server);
    if (networkInfo == null) continue;

    final successDownload = await GamedataDownloader.updateServerData(
      serverName: server,
      assetsBaseUrl: networkInfo['assetsUrl']!,
      saveDirectory: bundlesRoot,
      forceUpdate: forceUpdate,
    );

    if (successDownload) {
      final extractedDir = p.join(outputRoot, server);
      bool extractSuccess = await GamedataExtractor.extractServerBundles(
        server,
        bundlesRoot,
        outputRoot,
      );

      if (extractSuccess) {
        bool schemaSuccess = await FbsManager.ensureSchemasAvailable(server);

        if (schemaSuccess) {
          final schemasDir = FbsManager.getSchemaDirectory(server);

          print('[INFO] Starting massive decoding (Flatbuffers & AES)...');
          List<File> allBytesFiles = Directory(extractedDir)
              .listSync(recursive: true)
              .whereType<File>()
              .where((f) => f.path.endsWith('.bytes'))
              .toList();

          if (allBytesFiles.isNotEmpty) {
            final int numOfIso = max(Platform.numberOfProcessors - 1, 1);
            final int chunkSize = (allBytesFiles.length / numOfIso).ceil();
            List<List<String>> chunks = [];

            for (int i = 0; i < allBytesFiles.length; i += chunkSize) {
              chunks.add(
                allBytesFiles
                    .sublist(i, min(i + chunkSize, allBytesFiles.length))
                    .map((f) => f.path)
                    .toList(),
              );
            }

            print(
              '[INFO] Distributing ${allBytesFiles.length} files across ${chunks.length} threads...',
            );

            List<Future<void>> isolateTasks = [];
            for (int i = 0; i < chunks.length; i++) {
              final payload = DecodeTaskPayload(chunks[i], schemasDir, i);
              isolateTasks.add(
                Isolate.run(
                  () => _processChunkInIsolate(payload, verbose: verbose, failfast: failfast),
                ),
              );
            }

            await Future.wait(isolateTasks);
          } else {
            print('[WARN] No .bytes files found to process.');
          }

          // Restructure directories post-extraction and decoding
          _restructureOutput(server, outputRoot, bundlesRoot);

          print('[OK] All data from ${server.toUpperCase()} has been processed.');
        }
      }
    }
  }
  print('\n=== Pipeline Completed Successfully ===');
}
